-- پیام‌های قدیمی «فایل بزرگ» در صندوق پشتیبانی: شناسه‌ی بلند سفارش با شماره‌ی کوتاه (MJ-xxxx)
-- جایگزین و متن به راهنمای یکدست جدید (بدون ارجاع به تلگرام) تبدیل می‌شود.
UPDATE "SupportMessage" m
SET "text" = replace(m."text", o."id", 'MJ-' || o."orderNumber")
FROM "Order" o
WHERE m."sender" = 'support'
  AND m."userId" = o."userId"
  AND position(o."id" IN m."text") > 0;

UPDATE "SupportMessage"
SET "text" = regexp_replace(
  "text",
  '^فایل آیتم (\S+) سفارش (MJ-\d+) آماده است اما حجم آن بیش از ۲۰ مگابایت است و از طریق سایت قابل دانلود نیست\. برای دریافت لینک، همین‌جا به ما پیام بدهید\.$',
  'سفارش \2 (آیتم \1): حجم فایل بیش از ۲۰ مگابایت است و از صفحه‌ی سفارش‌ها قابل دانلود نیست. فایل شما آماده است. برای دریافت آن، لطفاً از بخش «پیام‌ها» در پنل خود به پشتیبانی پیام دهید.'
)
WHERE "sender" = 'support';
